"""
Мини-библиотека для генерации .map (TrenchBroom, Valve 220) под Tremble.
Масштаб: 64 юнита = 1 метр, Z — вверх.
"""

import os

FLOOR = ("game/Flor_Square", 0.5)
WALL = ("game/LowerWall", 0.15)
PAPER = ("game/PaperWall", 0.15)


class MapBuilder:
    def __init__(self, height=384, thickness=32):
        self.H = height
        self.T = thickness
        self.world = []
        self.entities = []

    # ------------------------------------------------------------------
    # Brushes
    # ------------------------------------------------------------------
    @staticmethod
    def box_text(x1, y1, z1, x2, y2, z2, tex=WALL):
        x1, x2 = min(x1, x2), max(x1, x2)
        y1, y2 = min(y1, y2), max(y1, y2)
        z1, z2 = min(z1, z2), max(z1, z2)

        if x2 - x1 < 1 or y2 - y1 < 1 or z2 - z1 < 1:
            return None

        name, s = tex
        f = lambda v: str(int(v))
        sc = f"0 {s} {s}"

        planes = [
            f"( {f(x1)} {f(y1)} {f(z1)} ) ( {f(x1)} {f(y1 + 1)} {f(z1)} ) ( {f(x1)} {f(y1)} {f(z1 + 1)} ) {name} [ 0 -1 0 0 ] [ 0 0 -1 0 ] {sc}",
            f"( {f(x1)} {f(y1)} {f(z1)} ) ( {f(x1)} {f(y1)} {f(z1 + 1)} ) ( {f(x1 + 1)} {f(y1)} {f(z1)} ) {name} [ 1 0 0 0 ] [ 0 0 -1 0 ] {sc}",
            f"( {f(x1)} {f(y1)} {f(z1)} ) ( {f(x1 + 1)} {f(y1)} {f(z1)} ) ( {f(x1)} {f(y1 + 1)} {f(z1)} ) {name} [ -1 0 0 0 ] [ 0 -1 0 0 ] {sc}",
            f"( {f(x2)} {f(y2)} {f(z2)} ) ( {f(x2)} {f(y2 + 1)} {f(z2)} ) ( {f(x2 + 1)} {f(y2)} {f(z2)} ) {name} [ 1 0 0 0 ] [ 0 -1 0 0 ] {sc}",
            f"( {f(x2)} {f(y2)} {f(z2)} ) ( {f(x2 + 1)} {f(y2)} {f(z2)} ) ( {f(x2)} {f(y2)} {f(z2 + 1)} ) {name} [ -1 0 0 0 ] [ 0 0 -1 0 ] {sc}",
            f"( {f(x2)} {f(y2)} {f(z2)} ) ( {f(x2)} {f(y2)} {f(z2 + 1)} ) ( {f(x2)} {f(y2 + 1)} {f(z2)} ) {name} [ 0 1 0 0 ] [ 0 0 -1 0 ] {sc}",
        ]

        return "{\n" + "\n".join(planes) + "\n}"

    def box(self, x1, y1, z1, x2, y2, z2, tex=WALL):
        b = self.box_text(x1, y1, z1, x2, y2, z2, tex)
        if b:
            self.world.append(b)

    def sealed_room(self, x1, y1, x2, y2, wall=WALL):
        """Закрытая комната: пол, потолок, 4 стены (внутренние границы x1..x2, y1..y2)."""
        T, H = self.T, self.H
        self.box(x1 - T, y1 - T, -T, x2 + T, y2 + T, 0, FLOOR)
        self.box(x1 - T, y1 - T, H, x2 + T, y2 + T, H + T, WALL)
        self.box(x1 - T, y1 - T, 0, x2 + T, y1, H, wall)
        self.box(x1 - T, y2, 0, x2 + T, y2 + T, H, wall)
        self.box(x1 - T, y1, 0, x1, y2, H, wall)
        self.box(x2, y1, 0, x2 + T, y2, H, wall)

    def pillar(self, cx, cy, size=64, tex=PAPER):
        self.box(cx - size, cy - size, 0, cx + size, cy + size, self.H, tex)

    def cover(self, x1, y1, x2, y2, h=80, tex=WALL):
        self.box(x1, y1, 0, x2, y2, h, tex)

    # ------------------------------------------------------------------
    # Entities
    # ------------------------------------------------------------------
    def entity(self, classname, props=None, brushes=None):
        lines = ["{", f'"classname" "{classname}"']
        for k, v in (props or {}).items():
            lines.append(f'"{k}" "{v}"')
        for b in brushes or []:
            lines.append(b)
        lines.append("}")
        self.entities.append("\n".join(lines))

    def point(self, classname, x, y, z, **props):
        p = {"origin": f"{int(x)} {int(y)} {int(z)}"}
        p.update({k: str(v) for k, v in props.items()})
        self.entity(classname, p)

    # Шаблоны забега
    def room_info(self, x, y, kinds, chapters="123"):
        self.point("room_info", x, y, 32, kinds=kinds, chapters=chapters)

    def room_entry(self, x, y):
        self.point("room_entry", x, y, 24)

    def room_exit(self, x, y, slot):
        self.point("room_exit", x, y, 8, slot=slot)

    def spawn(self, x, y, role="Any"):
        self.point("enemy_spawn", x, y, 16, role=role, arena="room")

    def crate(self, x, y, ammo=25):
        self.point("prop_AmmoCrate", x, y, 0, chip_ammo=ammo)

    # ------------------------------------------------------------------
    def write(self, path):
        out = [
            "// Game: Unity: Sin City",
            "// Format: Quake3 (Valve)",
            "// Generated by Tools/mapgen.py",
            "// entity 0",
            "{",
            '"mapversion" "220"',
            '"_tb_textures" "textures/game"',
            '"classname" "worldspawn"',
        ]
        for i, b in enumerate(self.world):
            out.append(f"// brush {i}")
            out.append(b)
        out.append("}")
        for i, e in enumerate(self.entities, start=1):
            out.append(f"// entity {i}")
            out.append(e)

        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(out) + "\n")

        print(f"Wrote {os.path.normpath(path)}: {len(self.world)} brushes, {len(self.entities)} entities")
